// Packs the Supabase reminders function (supabase/functions/reminders/index.ts) and the app code it uses
// into one file, dist-functions/reminders.ts, ready to paste into the Supabase dashboard's function editor.
import { build } from 'esbuild';

await build({
  entryPoints: ['supabase/functions/reminders/index.ts'],
  outfile: 'dist-functions/reminders.ts',
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  external: ['npm:*', 'node:*'],
  legalComments: 'none',
  banner: { js: '// Task Conquest reminders (generated by npm run build:reminders; edit supabase/functions/reminders/index.ts instead)' },
  logLevel: 'warning',
});
console.log('wrote dist-functions/reminders.ts');
